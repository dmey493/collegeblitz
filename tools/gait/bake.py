"""Bake the running gait tables in src/render/gait.js from CMU motion-capture clips.

  # from tools/gait, with the BVH files (github.com/una-dinosauria/cmu-mocap, data/0XX/XX_YY.bvh)
  for c in 35_17 35_18 09_01 09_05 35_22 16_46; do python3 extract.py $c.bvh > $c.json; done
  python3 bake.py
"""
import json
import os
KEYS = ['legFwd0', 'legFwd1', 'knee0', 'knee1', 'footPitch0', 'footPitch1', 'legAbd0', 'legAbd1',
        'armFwd0', 'armFwd1', 'armAbdTotal0', 'armAbdTotal1', 'elbow0', 'elbow1',
        'lean', 'bodyY', 'twist', 'hipTwist', 'roll']
GAITS = {'jog': ['35_17', '35_18'], 'run': ['09_01', '09_05'], 'fast': ['35_22', '16_46']}
out = {}
for name, clips in GAITS.items():
    rs = [json.load(open(c + '.json')) for c in clips]
    n = rs[0]['n']
    t = {}
    for k in KEYS:
        t[k] = [round(sum(r['table'][k][i] for r in rs) / len(rs), 3) for i in range(n)]
    # bounce about its own mean (the game sets the crouch)
    m = sum(t['bodyY']) / n
    t['bodyY'] = [round(v - m, 3) for v in t['bodyY']]
    out[name] = {
        'clips': [r['clip'].replace('.bvh', '') for r in rs],
        'speed': round(sum(r['speed'] for r in rs) / len(rs), 2),
        'stride': round(sum(r['stride'] for r in rs) / len(rs), 2),
        'n': n, 't': t,
    }
lines = ['// Running gait cycles measured from motion capture: the Carnegie Mellon University',
         '// Graphics Lab Motion Capture Database (mocap.cs.cmu.edu; free for research and commercial',
         '// use; the database was created with funding from NSF EIA-0196217), BVH conversion by',
         '// B. Hahne. Each clip was measured in the terms of our pose rig (thigh swing, knee bend,',
         '// foot pitch, upper-arm swing and spread, elbow bend, torso lean, shoulder and hip twist,',
         '// pelvis roll, hip bounce in leg lengths), folded into one symmetric stride that loops,',
         '// sampled 32 times per stride from the left thigh\'s furthest-forward point. Index 0 is',
         '// the right side, 1 the left. Generated by an offline script; not edited by hand.',
         '// speed: leg lengths per second, stride: leg lengths per stride, as captured.',
         'export const GAITS = {']
for name, g in out.items():
    lines.append(f"  {name}: {{ clips: {json.dumps(g['clips'])}, speed: {g['speed']}, stride: {g['stride']}, n: {g['n']}, t: {{")
    for k in KEYS:
        lines.append(f"    {k}: [{', '.join(str(v) for v in g['t'][k])}],")
    lines.append('  } },')
lines.append('};')
open(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', 'src', 'render', 'gait.js'), 'w').write('\n'.join(lines) + '\n')
print({k: (v['speed'], v['stride']) for k, v in out.items()})
